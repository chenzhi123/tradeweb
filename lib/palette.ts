export function canonicalSector(value: string | null | undefined): string | null {
  if (!value) return null;
  const key = value.trim().toLowerCase();
  if (!key || key === "-") return null;
  return ALIASES[key] ?? null;
}

export function sectorLabel(sector: string | null | undefined): string | null {
  if (!sector) return null;
  return SECTOR_ZH[sector] ?? sector;
}

export function sectorColor(sector: string | null | undefined): string {
  if (!sector) return "#8a8478";
  return SECTOR_COLOR[sector] ?? "#8a8478";
}

export function industryLabel(industry: string | null | undefined): string | null {
  if (!industry) return null;
  return INDUSTRY_ZH[industry] ?? industry;
}

export function categoryLabel(category: string | null | undefined): string | null {
  if (!category) return null;
  return CATEGORY_ZH[category] ?? category;
}
